ABOUT = ("date", "id", "shown", "said")  # 问的是哪一天的哪一条、问话里怎么说的、凭的是哪句原话


Source = tuple[int, int, int]  # 原话的出处：消息在收件箱第几行、在消息里从第几个字到第几个字


def unsure(said: str, what: str) -> str:
    """原话出自用户否定这件事的那句话本身、又说了同样的内容（见 refused_in）：再问一遍之前先说的话。
    what 是要不要做的那件事（“记”“按这个定”）。"""
    return f"你刚才说的是“{said}”，我没法确定要不要{what}。{HOW_TO_ANSWER}。"


