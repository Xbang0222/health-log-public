YES, NO, UNCLEAR = "yes", "no", "unclear"  # 用户的回答：明确的肯定、明确的否定或更正、判不出


# 引擎问的是“要删除吗”：删一条记录（R18），还是去掉一种食物的默认品种（R5）
DROP_RECORD, DROP_DEFAULT = "record", "default"


# 引擎问的是 hl add 的去重（R11，第十轮 C-5、D-5）：“是另外又吃了一份吗？”（AGAIN），
# 还是二选一的“是另外吃的、要补记上，还是要改这一餐？”（MORE，选项“补记”“改这一餐”）
AGAIN, MORE = "again", "more"


_PARTICLES = "的吧啊呀哈哦噢喔喽咯呗哒啦哇嘞呐诶欸哎"


_LEAVE = r"(?:不用|不要|不必|不需要|无需|别)再?(?:改|问|管|动|确认|担心)"  # 不用改、别担心


# 肯定词：回答去掉空白、常见的标点和语气词之后，整句完全由它们拼成（可以重复）才算确认。
# 只认短的、明确的
_SURE = r"对|是|嗯|恩|好|行|可以|没错|没问题|没毛病|确认|确定|正确|当然|ok|okay|yes"


_AS_IS = r"就这样|照记|记上?|就?[按照]这个[记定算来办]?"  # 照原样办：问的是“要删除吗”时分不清


# 引擎问的是“要删除吗”：这时“删吧、去掉、不要了”是同意，“不删、留着”才是否定
_DROP = r"删[掉了除]?|去掉|拿掉|划掉|不要了"


# 对一条记录说“撤销、撤掉”是同意删（R18）；问的是“要去掉默认品种吗”，多半是要取消这次操作（R5）
_UNDO_RECORD = r"撤销|撤掉"


# 对一条记录说“记错了、记重了”是该删（R18）；问的是“要去掉默认品种吗”，说的是“你弄错了”（R5）
_WRONG_RECORD = r"记错了|记重了|记多了"


_AFFIRM = re.compile(rf"(?:{_SURE}|{_AS_IS})+")


_AFFIRM_DROP = {
    DROP_RECORD: re.compile(rf"(?:{_SURE}|{_DROP}|{_UNDO_RECORD}|{_WRONG_RECORD})+"),
    DROP_DEFAULT: re.compile(rf"(?:{_SURE}|{_DROP})+"),
}


# 回答里只有空白、常见的标点（全角的已经折成半角）和语气词可以去掉。
# 别的符号、表情（❓🤔👍❌、引号、括号、破折号）都算多说了东西，判不出
_NOISE = re.compile(rf"[\s,.!~、;:。{_PARTICLES}]+")


_TRAIL = re.compile(r"\.{2,}|。{2,}")  # 省略号（…折成半角是三个点）、连着几个点或句号：在犹豫


_DIGIT = re.compile(r"[\d零〇一二两三四五六七八九十百千万半]")  # 带数字的回答都不算确认


_KEEP = re.compile(
    r"不[太大]?对|不是|不[太大]?行|不可以|不用|不必|不要(?!了)|[不别甭]\w{0,2}(?:[删撤]|去掉)"
    r"|留着|保留|别动"
)


_ERRORS = re.compile(r"错了|有误|[记称量输说看搞弄写填打]错")  # 去掉默认品种时，说“错了”是否定


# 说是另外吃的、要补记（MORE）。前面紧挨着否定词的（“不是另外吃的”“不用补记”“不补了”）
# 是说不是另外吃的，连着的几个词一起算（“不是另外又吃了一份”）
_SEPARATE = r"另外|补记|补上|又[吃喝]|还[吃喝]|多[吃喝]了"


_SEPARATELY = re.compile(_SEPARATE)


# 问“是另外又吃了一份吗”（AGAIN）时说这一份是另外吃的：只认“是另外、另外吃的、另外又吃”，
# 回答里顺带说的“还吃了个苹果、另外还喝了牛奶”说的是别的东西
_APART = re.compile(r"是另外|另外(?:又|再)?[吃喝]的|另外(?:又|再)[吃喝]")


_NOT_SEPARATE = re.compile(
    rf"(?:不是|并非|不用|不要|不必|无需|没有?|别|不)\s*(?:是\s*)?(?:(?:{_SEPARATE}|补)\s*)+"
)


# 要改那一餐（MORE 的“改这一餐”）：改、重说、记错了、只吃了、算了……；“不改、别改”不算
_CHANGE = re.compile(
    r"改|重说|重新|错|撤|删|只[吃喝有]|不记|别记|算了|取消|作废|重来|不要了|不用了"
)


_NO_CHANGE = re.compile(r"(?:不用|不要|不必|不|别|没)\s*改")


# 带着“不、没、别”字，但不是否定（“没记错、没称错”也是；“可不是”是附和）
_NOT_NO = re.compile(rf"没有?\w?错|没问题|没毛病|没事|{_LEAVE}|不要紧|不过|不错|可不是")


# 在问：吗、么、问号（❓❔‽；⁇⁈⁉ 折成半角带着 ?）、“呢”结尾、X不X（对不对、要不要、可不可以、
# 有没有，中间夹着空格也算）、“对吧、是吧”、谁让、什么、多少……
_ASKING = re.compile(
    r"吗|么|[?❓❔‽]|呢\W*$|(?<![不没])([^\W不没]\w?)\s*[不没]\s*\1|(?<!不)[对是]\s*的?\s*吧"
    r"|是否|谁|啥|咋|干嘛|多少"
)


# 明确的否定和更正：这件事作废。“不用、不必、不需要”也是（引擎给的选项里就有“不用”）
_RETRACT = re.compile(
    r"不[太大]?对|不是|不[太大]?行|不可以|不准|不要|不用|不必|不需要|不重建|不记|别记|别按|不算"
    r"|错了|有误|[记称量输说看搞弄写填打]错|改成|改为|改一下|要改|取消|算了|作废|重来"
)


# 用户后来又说要办时怎么重新问：默认用他否定之后说的那句话。原话要过字面核对的命令
# 换成自己的说法（redo），例如默认品种请用户连同食物名再说一遍（R19）
REDO = "用他在否定之后说的那句话不带确认调用，引擎会重新问"


# 用户说了不：先说这件事不办、不要再调用；再说用户说了新的、后来又要办时怎么办
def _fix_void(redo: str) -> str:
    return (
        f"{STOP}。用户同时说了新的（例如改了数字）：按新的原话重新调用，不要带确认。"
        f"用户后来又说要办：{redo}"
    )


def _fix_refused(redo: str) -> str:
    return (
        f"{STOP}，也不要拿原来那句话再问一遍。用户说了新的：按新的原话调用。"
        f"用户后来又说要办：{redo}"
    )


FIX_VOID = _fix_void(REDO)


FIX_REFUSED = _fix_refused(REDO)


def fix_refused(redo: str) -> str:
    """refusal 给的 fix（redo 见那里）：给自己查出用户否定过的命令用（hl undo 不给 --id，
    见 denied_about）。"""
    return _fix_refused(redo)


