"""餐次与日期用词、句法标记。"""

from __future__ import annotations

import re

from hl.language.units import CLAUSE_END

_MEAL_NAMES = (
    ("早餐", ("早餐", "早饭", "早点")),
    ("午餐", ("午餐", "午饭", "中饭")),
    ("晚餐", ("晚餐", "晚饭")),
    ("加餐", ("加餐", "零食", "夜宵", "宵夜", "下午茶")),
)

# 连着哪天一起说的餐次词（“今早”“昨晚”“前晚”）：说的是几天前的这一餐，
# 和“今天早上”“昨天晚上”“前天晚上”一样。“昨夜”同“昨天夜里”
_DAY_WORDS = {
    **dict.fromkeys(("今早", "今早上", "今晚", "今晚上"), 0),
    **dict.fromkeys(("昨早", "昨早上", "昨晚", "昨晚上", "昨夜", "昨夜里"), 1),
    **dict.fromkeys(("前晚", "前晚上"), 2),
    **dict.fromkeys(("大前晚", "大前晚上"), 3),
}


_MEAL_TIMES = (
    ("早餐", ("早上", "早晨", "今早", "今早上", "清早", "一早", "昨早", "昨早上")),
    ("午餐", ("中午", "晌午")),
    ("晚餐", (
        "晚上", "今晚", "今晚上", "傍晚", "昨晚", "昨晚上", "前晚", "前晚上", "大前晚", "大前晚上",
    )),
    ("加餐", ("上午", "下午", "睡前", "半夜", "深夜", "夜里", "昨夜", "昨夜里", "凌晨")),
)  # fmt: skip


MEAL_WORDS = tuple(word for _, words in (*_MEAL_NAMES, *_MEAL_TIMES) for word in words)


MEAL_NAMES = tuple(word for _, words in _MEAL_NAMES for word in words)  # 餐名，不含时间词


_NEXT_WORDS = ("后来", "然后", "接着", "之后", "随后", "过后", "又", "再", "还")


_PAUSE = re.compile(r"(?<=[\u4e00-\u9fff])\s+")  # 语音输入拿汉字后面的空格当停顿


_HALF_END = re.compile(rf"[{re.escape(CLAUSE_END)}]|{_PAUSE.pattern}")


_HALF_START = re.compile("|".join(sorted((*MEAL_WORDS, *_NEXT_WORDS), key=len, reverse=True)))

# 餐次词前面、后面有这些，说的不是这一餐的时间（“上次晚上吃的那种”“昨天晚上剩的”“早上买的”）
_NOT_THIS_MEAL = (
    re.compile(r"上次$"),
    re.compile(r"(?:的|吃|喝|没吃完|没喝完)*剩|[买做煮炒带留拿]的|打包"),
)

# 说是哪天的词，和它说的是几天前（第 6 节：从用户说这句话的那天往前数）。大前天是三天前，
# 不是前天；“昨个、前个”是口语里的昨天、前天
DAYS = {
    **dict.fromkeys(("今天", "今儿", "今儿个", "今日"), 0),
    **dict.fromkeys(("昨天", "昨儿", "昨儿个", "昨个", "昨个儿", "昨日", "昨"), 1),
    **dict.fromkeys(("前天", "前儿", "前儿个", "前个", "前个儿"), 2),
    **dict.fromkeys(("大前天", "大前儿", "大前儿个"), 3),
}


SAID_DAYS = ("", "昨天", "前天", "大前天")  # 几天前的那一天怎么说（请用户重说时用）

# “前晚”前面是这些字的，“前”是“之前、以前、三天前……”的“前”（“以前晚上不吃饭”）
_NOT_DAY_BEFORE = "之以睡饭从提事目当跟眼面门空向往年月周天日时课会赛战"


DAY_WORD = "|".join(
    f"(?<![{_NOT_DAY_BEFORE}])" * word.startswith("前") + word
    for word in sorted(DAYS, key=len, reverse=True)
)  # 认说是哪天的词用的正则，长的先认

# 餐次词前面说了是哪天的（“昨天晚上吃了一碗米饭”是昨天的晚餐，“昨儿晚上”“前儿中午”一样，
# “今天早上”明说了是今天）。后面跟着“的”的是在说那顿饭里的东西（“中午吃了昨天晚上的米饭”），
# 不是这一餐
_DAYS_AGO = re.compile(rf"(?P<day>{DAY_WORD})$")

# 哪天和餐次词中间隔着“的”的，半句开头说的、“是”后面说的才算（“昨天的早饭吃了两个鸡蛋”
# “应该是昨天的早饭”）；“中午吃了昨天的晚饭”“吃的是昨天的晚饭”说的是吃了什么，不算（见 _eaten）
_DAY_OF = re.compile(rf"(?:^|是)(?P<day>{DAY_WORD})的$")

# 说的是还没吃、打算以后吃的：说以后的（“明天早上打算吃一个苹果”“等会儿再喝”“下顿”），
# 打算、准备、想吃喝的（“晚上准备吃两个鸡蛋”）。“本来想吃”说的是没吃成，不算
_FUTURE = re.compile(r"明天|后天|明早|明晚|明儿|待会|等会|过会|一会儿|下次|下顿|下一顿")


_INTEND = re.compile(r"(?<!本来)(?<!原本)(?<!原来)(?:打算|准备|计划|想要?)(?:去|再|也)?[吃喝]")

# 说了吃了的（“吃了、吃过、吃完”“才吃的”“点了一碗”）。“一点了”“早点了”不是点菜
_EATEN = re.compile(
    r"[吃喝](?:了|过|完)|(?:才|就|刚|已经)[吃喝]的"
    r"|(?<![\d零一二两三四五六七八九十几早晚快慢多少好差有])点了"
)

# 想吃的那样没吃（“不想吃饭”“想吃火锅没去成”“准备吃面的，结果吃了两个鸡蛋”）
_MISSED = (
    r"[不没别](?=打算|准备|计划|想)|没(?:有|能)?(?:去|买|吃|喝|点|做|成|赶上|找到)|买不到"
    r"|结果|但是?|可是|不过|却"
)


_INSTEAD = re.compile(rf"\s*(?:{_MISSED}|最后|后来|只好|只能|还是)")


_AGAIN = re.compile(
    rf"(?:{'|'.join(sorted(MEAL_WORDS, key=len, reverse=True))}|后来|然后|接着|之后|随后|过后"
    r"|刚才|刚刚|刚|今天|我|就)*(?:又|再|还)(?:多|[吃喝来加干要点整]了?)*"
)


def _words_at(group: tuple[tuple[str, tuple[str, ...]], ...]) -> re.Pattern[str]:
    """一组餐次词，长的先认，认过的字不再认（“昨晚上”是一处，不是“昨晚”“晚上”两处）。"""
    words = sorted((word for _, words in group for word in words), key=len, reverse=True)
    guard = f"(?<![{_NOT_DAY_BEFORE}])"
    return re.compile("|".join(guard * word.startswith("前") + re.escape(word) for word in words))


_MEALS_OF = {word: meal for meal, words in (*_MEAL_NAMES, *_MEAL_TIMES) for word in words}


_GROUPS = tuple(_words_at(group) for group in (_MEAL_NAMES, _MEAL_TIMES))

# “<哪天>的<餐名>”前面说了吃喝、带、热、把（“中午吃了昨晚的夜宵”“吃的还是昨天的晚饭”
# “带的是”“热了”“把……吃了”“吃的昨天晚上的夜宵”）：说的是吃了那顿剩下的
_ATE = re.compile("(?:[吃喝带热][了过完掉剩]*(?:的[还就也都]?是?)?|把)$")

# 餐名前面说的是哪天那一顿：“昨天的晚饭”“昨天晚饭”“昨天晚上的晚饭”“昨晚的夜宵”“昨晚宵夜”
_PLAIN_TIMES = sorted((w for _, ws in _MEAL_TIMES for w in ws if w not in _DAY_WORDS), key=len)


_THAT_MEAL = re.compile(
    rf"(?:(?:{DAY_WORD})(?:{'|'.join(reversed(_PLAIN_TIMES))})?"
    rf"|{_words_at([('', tuple(_DAY_WORDS))]).pattern})的?$"
)

# 这一餐的餐次词后面接着“是”（“中午是”“午饭就是”“今天晚上也是”）：后面说的是这一餐吃了什么
_IS = re.compile("(?:[还就也都又只]|其实)*是$")

# 说几点吃的（“11点”“十一点半”“八点多”“11:30”）
_CLOCK = (
    r"(?:\d{1,2}[:：]\d{2}|(?:\d{1,2}|[零〇一二两三四五六七八九十]{1,3})[点时]"
    r"(?:半|钟|整|多|[一三]刻|(?:\d{1,2}|[零〇一二三四五六七八九十]{1,3})分?)?)(?:左右|前后|多)?"
)

# 吃的时候饿了（“饿了吃了宵夜”“饿醒了吃的”）：说的是怎么吃的这一餐，不是别的事
_HUNGRY = "(?:有点|太|好|很|实在|又)?饿(?:醒|坏|极)?了?"


_ADVERB = "(?:[我就只又也还都先才刚光约]|随便|简单|大概|大约|差不多)"

# 说吃了这一顿：“吃了”“吃的”“吃了顿”“吃了点”“吃了一顿”“喝了些”
_ATE_IT = "[吃喝](?:[了的过]?一?[顿点些个]|[了的过])?"

# 时间词和后面的餐名中间只说了吃（“昨晚吃的宵夜”“昨晚吃了顿宵夜”），几点吃的、饿了吃的
# （“昨晚11点吃的宵夜”“昨晚饿了吃了宵夜”），或者吃了什么、当作这一餐
# （“昨天早上吃了两个鸡蛋当早饭”“昨天早上八点吃了两个鸡蛋当早饭”“……算早饭”）：
# 时间词说的就是这一餐（第十轮 D-3）。说的是别的事（“昨晚没睡好吃了两个鸡蛋当早饭”）不算
_AS = r"(?:[当算]|作为)(?:作|做|成|是)?"


_AS_MEAL = re.compile(
    rf"{_ADVERB}*(?:{_CLOCK})?(?:{_HUNGRY})?{_ADVERB}*(?:{_ATE_IT}|[吃喝].*{_AS})"
)

# 时间词和后面的餐名中间说了吃，末尾这几个字说的是吃了这一顿（“没睡好吃了宵夜”的“吃了”）：
# 去掉它们之后还说了吃的，才是时间词那一餐另外吃了什么（见 _own_meal）
_ATE_IT_TAIL = re.compile(f"{_ATE_IT}$")

# 餐名后面的时间词后面只说了几点吃的（“夜宵吃了一碗米饭晚上十一点”“……晚上十一点吃的”）
_AT_CLOCK = re.compile(rf"{_CLOCK}(?:[才就]?[吃喝]的)?[的了啦呀吧哦]*")

# 和餐名说的是同一个时候的时间词（夜宵在晚上、夜里吃，下午茶在下午，早饭可以拖到上午）
_NIGHT = (
    "晚上", "今晚", "今晚上", "昨晚", "昨晚上", "前晚", "前晚上", "大前晚", "大前晚上",
    "夜里", "半夜", "深夜", "昨夜", "昨夜里", "凌晨", "睡前",
)  # fmt: skip


_SAME_TIME = {
    **dict.fromkeys(("夜宵", "宵夜"), _NIGHT),
    "下午茶": ("下午",),
    **dict.fromkeys(("早餐", "早饭", "早点"), ("上午",)),
}

# 只说了哪天、哪个时候的半句（“昨晚”“昨天”“昨天晚上”“昨晚11点”）：和后面隔着空格、逗号的
# 那半句连起来认（“昨晚 宵夜吃了一碗米饭”“昨天，晚上吃了一碗米饭”，第十轮 D-3）
_ALONE = re.compile(rf"(?=.)(?:{DAY_WORD})?(?:{_words_at(_MEAL_TIMES).pattern})?(?:{_CLOCK})?")


_JOINED = re.compile(r"[\s,，]+")  # 连起来认的两个半句中间只隔着这些

# 餐名和后面的时间词中间只有这些（“早饭上午十点才吃”“早饭是上午吃的”“早饭到中午才吃”）：
# 时间词说的是这一餐什么时候吃的
_WHEN = re.compile("(?:[是在于就也都还才又约到]|等到|拖到|一直到|大概|差不多)*")

# 时间词前面说的哪天（“早饭吃了两个鸡蛋昨天晚上……”的“昨天”）
_DAY_TAIL = re.compile(rf"(?:{DAY_WORD})的?$")

# 没吃的那一餐（“没吃早饭”）：后面紧跟着的时间词说的是另一餐
_SKIPPED = re.compile("(?:没有?|不|没顾上|没来得及|来不及)[吃喝]$")

# 餐次词后面说的没吃这一餐（“早饭没吃”“早上什么都没吃”“早饭没顾上吃”“早饭不吃了”“早饭没吃成”）。
# 后面接着说了没吃什么、吃得怎么样的（“早饭没吃饱”“早饭没吃米饭”“中午没吃什么”）说的是
# 这一餐吃了，不是没吃：要到半句末尾，或者后面接着说吃了别的、几点吃的（第十轮 D-4）
_SKIP_HOW = r"我?(?:[都也还又就]|根本|压根儿?|一直|(?:什么|啥)[都也])*"  # “什么都没吃”


_SKIP_AFTER = re.compile(
    rf"{_SKIP_HOW}"
    r"(?:没有?|没顾上|没来得及|来不及|没空|没时间|不)[吃喝](?:成|上)?(?:饭|东西)?[了啊呀的呢哦啦嘛]*"
    rf"(?=$|[\s,，吃喝就只光又再才后然]|{_CLOCK})"
)

# 说没吃那一餐之后接着说“就、只、随便……”吃了什么（“没吃早饭，就喝了一杯牛奶”）：
# 可能是拿它当了那一餐，也可能是后来另吃的
_INSTEAD_OF = re.compile(r"[\s,，]*我?(?:就|只|光|仅|随便|简单|凑合|将就)")

# 说几点吃的（“十二点吃了”“8:30吃的”）。“吃了一点米饭”的“一点”是份量
_ATE_AT = re.compile(rf"(?<![吃喝了些有点])({_CLOCK})(?=[才就又再先]?[吃喝])")

# 拿来比的（“比昨天晚上吃得少”“午饭比晚饭吃得多”“和昨天晚上一样”）不是说这一餐
_COMPARED = (
    re.compile("(?:比起?|不如)$"),
    re.compile("[和跟同像与]$"),
    re.compile("(?:吃的|的)?(?:一样|似的|差不多|相同|相比|比)"),
)
