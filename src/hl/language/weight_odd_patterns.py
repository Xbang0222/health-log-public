"""体重歧义数字、范围与旁注的词法规则。"""

from __future__ import annotations

import re

from hl.language.units import _ARABIC, _NUMBER, CLAUSE_END
from hl.language.weight_patterns import (
    _ABOUT,
    _CN_CHARS,
    _CN_WORD,
    _UNIT_END,
    _WEIGHT_UNIT,
    _WORD_END,
)

# 句号、逗号夹在两个数字中间、后面只有一两位（“78。5”“78,5kg”“78，5公斤”）：可能是写错的小数点，
# 也可能是两个数。后面三位的（“1,800”“78，200克”）、后面的数带着小数点的（“8:30,78.5”）是两个数
_ODD_POINT = re.compile(r"(?<![\d.])\d+[。,]\d{1,2}(?![\d.])")

# 不是 0-9 的数字（阿拉伯-印度数字“٧٨”、天城文数字“७८”；全角数字清理时已经折成了 0-9），
# 和阿拉伯小数点、千位符“٫٬”，连同挨着它们的数字和点：引擎读不全，“٧٨٫٥”只读出 78（K-8）
_FOREIGN_DIGITS = re.compile(r"[\d٫٬.]*(?:(?![0-9])\d|[٫٬])[\d٫٬.]*")

# 别的写错的小数点：两个点、点前后隔着空格、间隔号、点运算符、连字点、顿号、撇号（“78..5”“78. 5”
# “78 .5”“78·5”“78⋅5”“78‧5”“78、5”“78'5”），隔着空格的一位数（“78 5”，第九轮 W-5；
# “78 1/2”是分数，见 _SPACED_FRACTION）。
# 前面只认两三位数：“1. ”是序号，“1、2个”说的是一两个，“5'11”是身高
_ODD_SEPARATOR = re.compile(
    r"(?<![\d.])\d{2,3}(?:(?:\.{2,}|\.\s+|\s+\.\s*|[·・•∙⋅‧、'’′])\d{1,2}|\s+\d(?![/⁄]))(?![\d.])"
)

# 分数（“78½”“78 1⁄2”）：折成半角时“½”会拆成“1⁄2”，“78½”就成了 781；在原话里先挑出来
_FRACTION = re.compile(r"(?:\d+\s*)?[\u00bc-\u00be\u2150-\u215f\u2189]|\d+\u2044\d+")

# 上标、下标数字（“78.5²”“⁷⁸.⁵”“78.5₂”）：折成半角就成了普通数字，“78.5²”成了 78.52（第九轮 W-7）。
# 在原话里先挑出来；跟在字母后面的是单位、化学式（“m²”“CO₂”），不算
_SCRIPT_DIGIT = "\u00b2\u00b3\u00b9\u2070\u2074-\u2079\u2080-\u2089"


_SCRIPTED = re.compile(rf"(?<![a-zA-Z])[\d.]*[{_SCRIPT_DIGIT}][\d.{_SCRIPT_DIGIT}]*")

# 用斜杠写的带分数（“78 1/2”“156 1/2斤”“78又1/2”“78-1/2”）：“1/2”会被当成日期涂掉，剩下 78。
# 在涂日期之前挑出来。中文写的“78又二分之一”“七十八又二分之一”也是（第九轮 W-5）
_SPACED_FRACTION = re.compile(
    r"(?<![\d./])\d{2,3}(?:\s+|\s*[又-]\s*)[1-9]/[1-9]\d?(?![\d/.])"
    rf"|(?:(?<![\d.])\d{{2,3}}|(?<![{_CN_CHARS}])[{_CN_CHARS}]{{2,}})"
    rf"\s*又\s*[{_CN_CHARS}]+分之[{_CN_CHARS}]+"
)

# “数 点 数”：“点”前后都是数（阿拉伯数字或中文数字），中间可能夹着空格
_DIAN_PAIR = re.compile(rf"(?<![\d.{_CN_CHARS}])(\d+|[{_CN_CHARS}]+)(\s*点\s*)(\d+|[{_CN_CHARS}]+)")

# 约数（“150多斤”“七十几公斤”）：截成 150、70 照记不对。中文的约数落在十、百、千上（“我一来就称了”
# 不是约数）。隔着空格的“150 多斤”也是；小数后面隔着空格的“多”不是（“77.6 多吃了一点”）
_ROUGH_NUMBER = rf"(?:{_ARABIC}|[{_CN_CHARS}]*[十百千])[{_ABOUT}]|(?<![\d.])\d+\s+[{_ABOUT}]"


_ROUGH_NUMBER += rf"|(?<![{_CN_CHARS}])[{_CN_CHARS}]*[十百千]\s+[{_ABOUT}]"

# 小数那位没说：“78点几”“78点多”“七十八点几”“78.x”“78.几”。“8点多”“七点几”是钟点，
# 认约数之前已经涂掉了（见 without_times）
_ROUGH_NUMBER += rf"|(?<![\d.{_CN_CHARS}])(?:\d+|[{_CN_CHARS}]+)点[多几]"

# “78.几”“78.多”“78.xx”“78.?”（第九轮 W-5）；“.”后面用别的符号占着小数那位的
# “78.*”“78.…”“78.△”（第十轮 W-8）。半句完的标点（“78.，”）不算
_ROUGH_NUMBER += r"|(?<![\d.])\d+\.(?:x+(?![a-z])|[多几?]"


_ROUGH_NUMBER += rf"|[^\w\s.{re.escape(CLAUSE_END)}]|\.+(?![\d.]))"  # “78..5”是写错的小数点


_ROUGH = re.compile(
    rf"(?P<spot>(?P<num>{_ROUGH_NUMBER}))\s*(?:(?P<unit>{_WEIGHT_UNIT}){_UNIT_END})?",
    re.IGNORECASE,
)

# 说约数的别的说法：单位后面紧跟“多”（“150斤多”“80公斤还多”）；数或单位后面的“左右、上下、
# 出头、前后、附近、的样子”和上下限“以上、以下、以内、开外、往上、不到、+”（“150斤+”“150+斤”），
# 中间可以夹“还、刚”（“80公斤还不到”“刚出头”）；数前面的“大概、大约、约、差不多、将近、接近、
# 估计、约莫、估摸、大致、好像”和上下限“超过、不到、没到、不够、不满、破、刚过、差点、几乎、快、
# 近、至少、少说、撑死、≈、~、>”；中文输入法打出的“《》〈〉”（Shift+, Shift+.）和“‹›«»”
# 也是小于、大于，数或单位后面的“一下”是“以下”的同音字（第九轮 W-2）。
# 隔着括号、逗号、冒号的也是（“80公斤（以下）”“78.5公斤，左右”“（约）78.5”“大约：78.5”，W-5）。
# 约数词、上下限词后面跟着“~”的（“大约~78.5”“超过~80”），“>=、<=、》=、大于等于、小于等于”
# 也是（第十轮 W-6）。
# 不算的：“上下班”“上下午”“以下是……”“以上就是”“不到两周”（“不到”说的是后面的数）、“不到中午”
# （“不到”后面连着别的字）、“+0.3”、“最近、附近、很快、吃得快、愉快”、“很不满、摔破、打破”、
# “非常不满”、成对的书名号括着字的“《体重》”（第十轮 W-9，见 _title_mark）、
# 箭头“->”、颜文字里的“<”（“>_<”）、汉字或字母后面拖长音的“~”（“早~78.5kg”“hi~78.5”，
# 说体重的词后面的照旧是约数，“体重~78.5”，见 _drawn_out）
_NOT_ENOUGH = rf"(?!\s*[\d{_CN_CHARS}半]){_WORD_END}"


_AROUND = r"左右|上下(?![班楼车午课学])|出头|以上(?![是为就])|以下(?![是为就])|开外"


_TAIL_WORDS = (
    rf"{_AROUND}|[以之]内|往上|往下|朝上"
    rf"|前后{_WORD_END}|附近{_WORD_END}|的样子|不到{_NOT_ENOUGH}|不足{_NOT_ENOUGH}|\+(?!\s*\d)"
    # 数或单位后面的“一下”是“以下”（拼音 yixia 的首选词）；“一下子”是突然，“一下午、一下班”不是
    r"|一下(?![子是为就午班])"
)

# 括号里的（“（以下）”）；逗号后面的只认左右、上下、出头、以上、以下、开外（“，附近的药店”不是）
_ROUGH_TAIL = rf"(?:\(\s*(?:{_TAIL_WORDS})\s*\)|,\s*(?:{_AROUND})|(?:[还刚]\s*)?(?:{_TAIL_WORDS}))"


_HEDGE = (
    r"(?:大概|大约|约莫|约|差不多|将近|接近|估计|估摸|大致|好像|似乎|不超过|超过|超出|高于|低于"
    r"|大于等于|小于等于|大于|小于|多于|少于|不到|不足|没到|没有|不够|不止|刚过"
    # 程度副词后面的“不满”是不满意（“很不满、非常不满”，第十轮 W-9）
    r"|(?<![很太摔打挺超蛮更最极])(?<!非常)(?<!特别)(?<!十分)(?<!相当)(?<!极其)(?<!比较)"
    r"(?<!有点)(?<!有些)(?<!尤其)不满"
    r"|(?<![很太摔打])破"
    r"|差点|几乎|至少|少说|起码"
    r"|最多|顶多|撑死|快要|快到"
    r"|(?<![很太较飞赶尽加凉痛爽得蛮挺真好越更最愉欢轻畅])快"
    r"|(?<![最附靠贴亲临邻就远将接])近|[≈≥≤≧≦]|(?<!_)[~〜]"
    r"|(?<!_)[<《〈‹«]=?|(?<![-=])[>》〉›»]=?)\s*\)?\s*(?:是|有|在|了)?\s*:?\s*[~〜]?\s*"
)


_ROUGHLY = re.compile(
    rf"(?P<spot>(?<![\d.{_CN_CHARS}])(?P<num>{_ARABIC}|{_CN_WORD})\s*"
    rf"(?:(?P<unit>{_WEIGHT_UNIT}){_UNIT_END}半?(?:还多{_WORD_END}|多|\s*{_ROUGH_TAIL})"
    rf"|{_ROUGH_TAIL}(?:\s*(?P<tail_unit>{_WEIGHT_UNIT}){_UNIT_END})?))"
    rf"|(?P<hedged>{_HEDGE}(?P<said>{_ARABIC}|{_CN_WORD}))(?:\s*(?P<said_unit>{_WEIGHT_UNIT}){_UNIT_END})?",
    re.IGNORECASE,
)

# 约数后面跟着这些量词，说的是别的量（“二十多天”“将近30次”“差不多30圈”），不是体重的约数
_MEASURE_WORDS = (
    "天", "日", "个", "次", "周", "星期", "礼拜", "月", "年", "岁", "分钟", "分", "秒", "小时",
    "钟头", "步", "遍", "下", "回", "顿", "餐", "圈", "组", "页", "人", "块", "元", "米", "公里",
    "层", "件", "只", "根", "颗", "杯", "碗", "瓶", "口", "片", "张", "串", "粒", "罐", "条",
    "盒", "袋", "包(?![括含])", "份", "勺", "盘", "卡", "度(?![过假])", "cc",
)  # fmt: skip


_OTHER_AMOUNT = re.compile(
    rf"\s*(?:{'|'.join(sorted(_MEASURE_WORDS, key=len, reverse=True))})", re.IGNORECASE
)

# 带着别的单位的数，一看就不是体重（中间可以有“多、来”：“200多克”“五十多岁”）。
# 单位只收不会是下一个词开头的：“个、天、周、餐、月”这类单字量词也是“个人、天天、周末、餐后、
# 月初”的头一个字，“77.6 餐后 78.3”不能把 77.6 涂掉；“70卡着不动”的“卡”说的是不动，也不算。
# “卡”要紧挨着数；别的可以隔着空格（语音输入的“大约 100 克”“200 多克”“250 毫升”“50 岁”），
# “78.5 克服了”“克制”的“克”、“岁月”的“岁”不是单位。英石、盎司、台斤、港斤也在这里：
# 换算成公斤像体重的由调用方整句拒绝（见 odd_weight_units），剩下的说的是别的东西（“喝了8oz咖啡”）。
# 厘米、公分、cm 是身高，另外认（见 _weight_marks）
_OTHER_UNITS = (
    "卡(?![着住在])"
    r"|\s*(?:千卡|大卡|卡路里|分钟|小时|公里|毫升|毫米|毫克|岁(?!月)|块钱|元钱|(?<!千)克(?![服制]))"
    r"|\s*(?:英石|盎司|台斤|港斤|司马斤|(?:kcal|km|ml|mm|mg|cc|g|stones?|st|oz)(?![a-z]))"
)


_DECIMAL = r"\d+(?:[.点]\d+)?"

# 一看就不是体重的数，连“点”一起涂掉：百分比（千分比、万分比也是）、
# 序数（“第3”“22nd”“23rd”“25th”；“21st”见 odd_weight_units）、
# 带着别的单位的数（“5点5公里”“体脂22点5%”）
_ASIDES = re.compile(
    rf"{_DECIMAL}\s*[%‰‱]|百分之{_NUMBER}|第\s*{_NUMBER}|(?<![\d.])\d+(?:nd|rd|th)(?![a-z])"
    rf"|(?:{_DECIMAL}|{_CN_WORD})(?:\s*[{_ABOUT}])?(?:{_OTHER_UNITS})",
    re.IGNORECASE,
)
