"""体重数字、单位、时间与不完整写法的词法规则。"""

from __future__ import annotations

import re

from hl.language.units import _ARABIC, _NUMBER, CLAUSE_END

_THOUSANDS = re.compile(r"(?<![\d.,])\d,\d{3}(?![\d,])")  # “1,800”这种千位分隔的写法


_WIDE_COMMA = re.compile(r"(?<=\d)，(?=\d)")


KG_PER = {"公斤": 1.0, "斤": 0.5, "磅": 0.45359237}  # 一个单位合多少公斤（R16）


PLAUSIBLE_KG = (20, 300)  # 换算成公斤不在这个范围里的数不会是体重（R16）


_WEIGHT_UNITS = {"公斤": "公斤", "千克": "公斤", "kg": "公斤", "kgs": "公斤"}


_WEIGHT_UNITS |= {"斤": "斤", "市斤": "斤"}

# “镑”“英镑”是常见错字：和“磅”同音，输入法里最常挑错
_WEIGHT_UNITS |= {"磅": "磅", "镑": "磅", "英磅": "磅", "英镑": "磅", "lb": "磅", "lbs": "磅"}


_WEIGHT_UNITS |= {"pound": "磅", "pounds": "磅"}

# 长的先认：“公斤”在“斤”前面，lbs 在 lb 前面
_WEIGHT_UNIT = "|".join(sorted(_WEIGHT_UNITS, key=len, reverse=True))

# 字母单位后面不能再连着字母（“lb”不是“lbx”的头）；斤、公斤、磅后面连着字母照样是单位
# （“156斤hhh”是 156 斤，hhh 是多出来的字）。“磅”后面不能是“秤”（“78.5 磅秤上称的”不是 78.5 磅）
_UNIT_END = r"(?!(?<=[a-z])[a-z]|(?<=[磅镑])秤)"


_WEIGHED = rf"\s*(?:{_WEIGHT_UNIT}){_UNIT_END}"  # 紧跟着体重单位


_CN_CHARS = "零〇一二两三四五六七八九十百千"

# 体重里的中文数字。“两”跟在别的中文数字后面是重量单位“两”（“二两”“三两天”），不算进数里；
# “千克”的“千”是单位（“七十五千克”不是七十五千）
_NOT_LIANG = "零〇一二三四五六七八九十百千"


_CN_INT = rf"(?!千克)[{_CN_CHARS}](?:(?!千克)[{_NOT_LIANG}]|两(?=[{_NOT_LIANG}]))*"


_CN_WORD = rf"{_CN_INT}(?:点[零〇一二三四五六七八九]+)?"

# 单位后面的“半”是半个单位：后面得是句末、空白、标点或语气词；“78公斤半个月”说的是半个月
_WORD_END = r"(?=$|\W|[了啊呀呢吧哦嘛的哈])"


_HALF = rf"(?P<half>半){_WORD_END}"

# 斤后面的“M两”“零M两”：一两是十分之一斤（“155斤2两”是 155.2 斤）。“公斤”后面的不算；
# “两”后面连着别的字的不算（“150斤 一两个星期”）
_LIANG = rf"(?<=斤)(?<!公斤)\s*零?\s*(?P<liang>[1-9](?![\d.])|[一二三四五六七八九])\s*两{_WORD_END}"

# 斤后面还跟着没读进来的数（“124斤6”“一百二十四斤六”“156斤 半”“124斤16两”）：口语里多半是
# 几两、半斤，认不准。只认一位数和“半”：“瘦了两斤 77.6”“两斤 七十”后面是另一个数
_JIN_LEFTOVER = re.compile(
    rf"\s*零?\s*(?:(?:[1-9]|[一二三四五六七八九]|半)(?![\d.]){_WORD_END}|\d+(?=\s*两))"
    r"|\.\d+"  # “156斤.5”：小数点写到了单位后面
)

# 公斤、磅后面还跟着没读进来的一位数或“半”（“78公斤5”“七十八公斤五”“78 公斤 半”），
# 或者紧跟着“.数”（“78公斤.5”“78kg.5”）：可能是小数，也可能是别的
_UNIT_LEFTOVER = re.compile(rf"\s*(?:[1-9]|[一二三四五六七八九]|半)(?![\d.]){_WORD_END}|\.\d+")

# 原话里的每个数，连同紧跟着的体重单位（“一千克”是 1 公斤）。
# 没带单位的中文数字也是数，见 _weight_marks
_WEIGHT = re.compile(
    rf"(?:(?P<num>{_ARABIC})|(?P<cn>{_CN_WORD}))"
    rf"(?:\s*(?P<unit>{_WEIGHT_UNIT}){_UNIT_END}(?:{_HALF}|{_LIANG})?)?",
    re.IGNORECASE,
)


_SAID_AS = r"(?:是|为|有|约|大概|大约|差不多|[:\s])*$"  # “身高是 175”“身高：175”里夹在中间的词

# “身高 175”“1 米 75”“一米七五”的 75。“米”前面只能是 1、2（“1500米 70.5”的“米”是距离）
_AFTER_HEIGHT = re.compile(rf"(?:身高{_SAID_AS}|(?<![\d.{_CN_CHARS}])[12一两]\s*米\s*$)")


_HEIGHT_UNIT = re.compile(r"\s*(?:cm|厘米|公分)", re.IGNORECASE)


_METRES = re.compile(r"\s*米")  # “1.75 米”；“77.6 米饭”的“米”不是身高，只认 3 以下的数

# 数后面紧跟着的、不是体重单位的字母（“172 Ibs”是 lbs 打错了，“78 kilos”）：写了单位，只是引擎不认
_LETTERS = re.compile(r"\s*([a-z]+)", re.IGNORECASE)

# 单说了单位：只认明说的（“单位是斤”“按斤算”“我说的是磅”“（斤）”、单独成句的“斤”、
# “是斤不是公斤”“是斤哦”，写在数前面、隔着冒号斜杠空格的“斤：156”“lbs: 172”“斤数 156”
# “体重/斤：156”——单位前面是句首、空白、标点或“体重”，跟在别的数后面的“瘦了2斤 70”不算）。
# “上磅、过磅、磅秤”“轻了一斤”“半斤饺子”“不按斤算”“可以磅一下”
# 里的斤、磅都不是在说体重的单位；问句、问换算的也不是（见 _unit_note）
_PARTICLES = "的啊哦呢吧哈"


_UNIT_NOTE = re.compile(
    rf"(?:单位(?:是|为|用|:)?|说的是|指的是|我是说)\s*(?P<told>{_WEIGHT_UNIT}){_UNIT_END}"
    rf"|(?<!不)按\s*(?P<by>{_WEIGHT_UNIT}){_UNIT_END}(?=\s*[算计记来说的])"
    rf"|[(\[]\s*(?P<bracket>{_WEIGHT_UNIT})\s*[)\]]"
    rf"|(?:^|[{CLAUSE_END}])\s*(?:是|都是)?(?P<alone>{_WEIGHT_UNIT})[{_PARTICLES}]*\s*(?=$|[{CLAUSE_END}])"
    rf"|(?<!不)是\s*(?P<is>{_WEIGHT_UNIT}){_UNIT_END}"
    rf"(?=\s*,?\s*而?不是|[{_PARTICLES}]*\s*(?:$|[{CLAUSE_END}]))"
    rf"|(?:^|(?<=[\s/:{CLAUSE_END}])|(?<=体重))(?P<before>{_WEIGHT_UNIT}){_UNIT_END}数?"
    rf"(?=\s*[:/]?\s*[\d{_CN_CHARS}])",
    re.IGNORECASE,
)


_DIGITS_AND_CN = frozenset("0123456789" + _CN_CHARS)


_BY_VERB = re.compile(r"\s*[算计记来说]?")  # “按斤算”的“算”


_NOT_A_NOTE = ("多少", "换算", "?", "吗")  # 这个分句是在问（“单位是斤吗？”“按斤算是多少”）

# 原话里说到的体重单位（不论跟没跟在数后面）；“上磅、过磅、磅重”的“磅”说的是称，另外去掉
_UNIT_WORD = re.compile(rf"(?<![a-z])(?:{_WEIGHT_UNIT}){_UNIT_END}", re.IGNORECASE)


_SCALE_VERBS = ("上磅", "过磅", "磅重", "上镑", "过镑", "镑重")

# 数（R16 看体重一眼清不清楚用）：阿拉伯数字串、中文数字各算一个；几个明显不是在说数的词不算
_ANY_NUMBER = re.compile(rf"\d+(?:\.\d+)?|[{_CN_CHARS}万半]+")


_NOT_NUMBERS = (
    "一下", "一直", "一起", "一样", "一定", "一般", "一些", "一边", "一切", "统一", "唯一",
    "称一称", "量一量", "测一测",
)  # fmt: skip

# 引擎不认的重量单位：一英石、一盎司合多少公斤（只用来看那个数像不像体重，不拿来换算记下）
_ODD_KG = {"英石": 6.35029318, "stone": 6.35029318, "stones": 6.35029318, "st": 6.35029318}


_ODD_KG |= {"盎司": 0.028349523125, "oz": 0.028349523125}

# 台斤 0.6 公斤，港斤（司马斤）约 0.605 公斤：不是市斤，引擎不换算，也不能当公斤记（K-9）
_ODD_KG |= {"台斤": 0.6, "港斤": 0.60478982, "司马斤": 0.60478982}


_ODD_UNIT = re.compile(
    rf"(?P<n>{_NUMBER})\s*(英石|stones?|st|盎司|oz|台斤|港斤|司马斤)(?![a-z])", re.IGNORECASE
)


_ABOUT = "多几来余"  # 约数：“150多斤”“七十几”“200来克”

# “N点M”后面紧跟着体重单位：是小数，不是钟点
_UNIT_AFTER = re.compile(_WEIGHED, re.IGNORECASE)

# 明确的钟点：数字跟“点”，后面是半、一刻、三刻、整、钟、X分（“7点半”“8点一刻”“十点二十分”），
# 或者“点”后面直接不是数字（“8点称的”“七点多”）。后面的数自己带着小数点（“8点 78.5”），
# 或者隔着空格、自己带着体重单位（语音输入的“8点 78公斤”“多吃了一点 七十七点六公斤”），
# 这个“点”就不会是小数点，也算。“8点5”“七点三十”钟点、小数都说得通，不算
_HOUR = re.compile(
    rf"(?<![\d.{_CN_CHARS}])"
    r"(\d{1,2}|二?十[一二三四五六七八九]?|[零〇一二两三四五六七八九])\s*点"
    r"(?:\s*(?:半|整|钟|[一三]刻|(?:\d{1,2}|[零〇一二三四五六七八九十]{1,3})\s*分)"
    rf"|(?!\s*(?:\d+(?!\d|\.\d)|[{_CN_CHARS}]))"
    rf"|(?=\s+(?:{_ARABIC}|{_CN_WORD}){_WEIGHED}))",
    re.IGNORECASE,
)

# 月后面的几号（“10月28”）：1～31，阿拉伯数字或中文数字
_MONTH_DAY = (
    r"(?:(?:3[01]|[12]?\d)|(?:三十一?|[一二]?十[一二三四五六七八九]?|[一二三四五六七八九]))"
    rf"(?![\d.{_CN_CHARS}号日]|\s*(?:{_WEIGHT_UNIT}))"
)

# 日期：“8:30”“2026-10-08”“10/8”，数紧跟着“年、月、号、日”（“10月8号”“二十八号”）。
# 前面紧挨着数字或小数点的不算（“77.6 月经”“77.6 日常”的 6 是小数）；月不过 12，号、日不过 31，
# “号、日、年”要紧挨着数（“孩子体重 25 号称的”不涂）；年份是四位数或逐位读的中文数字
# （“2026年”“二零二六年”，“80年初”的 80 不涂）。“10月28”“十月二十八”没说号也是日期：
# 月后面跟着不过 31 的数，后面不是号、日、小数点、体重单位（“12月 70公斤”的 70 不涂）。
# 换算成公斤像体重的数，这一条涂不掉几个
_DATES = re.compile(
    r"(?<![\d.])(?:(?P<hour>\d{1,2}):\d{2}(?::\d{2})?"
    r"|\d{4}[/-]\d{1,2}[/-]\d{1,2}"
    r"|(?P<month>\d{1,2})[/-](?P<day>\d{1,2}))(?![\d.])"
    rf"|(?<![\d.点{_CN_CHARS}])(?P<n>\d+|[{_CN_CHARS}]+)(?:\s*(?P<m>月)(?:\s*{_MONTH_DAY})?|(?P<d>[号日])(?!常|记)|(?P<y>年))"
)

# 认得准的小数点：“点”前面的数大于 24（不会是钟点）；或者后面紧跟着体重单位、只有按小数读
# 才像体重（“22点5公斤”，见 _POINT_UNIT）；或者“点”前面是 0、后面没有“分”
# （“轻了0点3”：钟点不这么说）
_POINT = re.compile(
    rf"(?<![\d.])(?P<whole>\d+)点(?=\d+(?P<unit>{_WEIGHED})?(?P<minute>\s*分)?)", re.IGNORECASE
)

# “N点M”后面紧跟着体重单位、N 不超过 24：可能是小数（“22点5公斤”），也可能是 N 点钟称的
# M 个单位（“8点70公斤”“十点六十五公斤”）。两种读法换算成公斤哪种像体重按哪种，
# 都像的认不准（见 _clock_or_point）
_POINT_UNIT = re.compile(
    rf"(?<![\d.{_CN_CHARS}])(?P<n>\d{{1,2}}|[{_CN_CHARS}]+)点(?P<m>\d+|[{_CN_CHARS}]+)"
    rf"(?=\s*(?P<unit>{_WEIGHT_UNIT}){_UNIT_END})",
    re.IGNORECASE,
)
